CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'kasir')) DEFAULT 'kasir',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS produk (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_barang TEXT NOT NULL,
    barcode TEXT UNIQUE,
    kode_sku TEXT NOT NULL UNIQUE,
    harga_beli NUMERIC(14, 2) NOT NULL DEFAULT 0,
    harga_jual NUMERIC(14, 2) NOT NULL DEFAULT 0,
    stok INTEGER NOT NULL DEFAULT 0,
    stok_minimum INTEGER NOT NULL DEFAULT 5,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sesi_shift (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    waktu_mulai TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    waktu_selesai TIMESTAMPTZ,
    status_sesi TEXT NOT NULL CHECK (status_sesi IN ('aktif', 'selesai')) DEFAULT 'aktif',
    modal_awal NUMERIC(14, 2) NOT NULL DEFAULT 0,
    kas_aktual_akhir NUMERIC(14, 2),
    selisih_kas NUMERIC(14, 2),
    catatan_shift TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_one_active_shift_per_user
    ON sesi_shift(user_id) WHERE status_sesi = 'aktif';

CREATE TABLE IF NOT EXISTS transaksi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomor_invoice TEXT NOT NULL UNIQUE,
    sesi_shift_id INTEGER NOT NULL REFERENCES sesi_shift(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    kasir_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    waktu_transaksi TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total_harga NUMERIC(14, 2) NOT NULL DEFAULT 0,
    metode_pembayaran TEXT NOT NULL CHECK (
        metode_pembayaran IN ('tunai', 'qris', 'debit', 'kredit', 'transfer')
    ) DEFAULT 'tunai',
    jumlah_bayar NUMERIC(14, 2) NOT NULL DEFAULT 0,
    kembalian NUMERIC(14, 2) NOT NULL DEFAULT 0,
    status_transaksi TEXT NOT NULL CHECK (status_transaksi IN ('selesai', 'batal')) DEFAULT 'selesai',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detail_transaksi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_id INTEGER NOT NULL REFERENCES transaksi(id) ON UPDATE CASCADE ON DELETE CASCADE,
    produk_id INTEGER NOT NULL REFERENCES produk(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    jumlah_beli INTEGER NOT NULL CHECK (jumlah_beli > 0),
    harga_satuan NUMERIC(14, 2) NOT NULL,
    harga_beli_satuan NUMERIC(14, 2) NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_produk_barcode ON produk(barcode);
CREATE INDEX IF NOT EXISTS idx_produk_sku ON produk(kode_sku);
CREATE INDEX IF NOT EXISTS idx_shift_status ON sesi_shift(status_sesi);
CREATE INDEX IF NOT EXISTS idx_shift_user ON sesi_shift(user_id);
CREATE INDEX IF NOT EXISTS idx_transaksi_shift ON transaksi(sesi_shift_id);
CREATE INDEX IF NOT EXISTS idx_transaksi_waktu ON transaksi(waktu_transaksi);
CREATE INDEX IF NOT EXISTS idx_transaksi_metode ON transaksi(metode_pembayaran);
CREATE INDEX IF NOT EXISTS idx_detail_transaksi ON detail_transaksi(transaksi_id);
CREATE INDEX IF NOT EXISTS idx_detail_produk ON detail_transaksi(produk_id);

